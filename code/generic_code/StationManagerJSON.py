"""Utilities for managing station metadata exported in JSON format.

This class is designed to work with station data generated by station_pipeline.py
(the `export_data` output), where data is organized by year and station code.
"""

from __future__ import annotations

from typing import Any
import copy
import json
import os
import pprint as pp
import tempfile

from .ContaminantManagerJSON import ContaminantManagerJSON


class StationManagerJSON:
    """Manager for station metadata loaded from JSON or in-memory dictionaries.

    Expected structure:
        {
            "2019": {
                "4": {
                    "station_name": "...",
                    "contaminant_code": [1, 10, 110],
                    "contaminant_names": ["SO2", "PM10", "PM10"],
                    ...
                },
                ...
            },
            "2021": {
                ...
            }
        }
    """

    def __init__(
        self,
        file_path: str | None = None,
        station_data_by_year: dict[str, Any] | None = None,
        contaminant_manager: ContaminantManagerJSON | None = None,
    ) -> None:
        if file_path is None and station_data_by_year is None:
            raise ValueError("Either file_path or station_data_by_year must be provided.")

        if file_path is not None and station_data_by_year is not None:
            raise ValueError("Provide only one source: file_path or station_data_by_year.")

        self._stations_data_by_year: dict[str, Any] = {}

        if file_path is not None:
            with open(file_path, encoding="utf-8") as json_file:
                self._stations_data_by_year = json.load(json_file)
        else:
            self._stations_data_by_year = copy.deepcopy(station_data_by_year)

        self._contaminant_manager = contaminant_manager

    def __repr__(self) -> str:
        years = self.get_available_years()
        total_stations = sum(len(self._stations_data_by_year[str(y)]) for y in years)
        return (
            f"{self.__class__.__name__}("
            f"years={years}, "
            f"year_count={len(years)}, "
            f"station_entries={total_stations})"
        )

    @classmethod
    def from_pipeline_export_data(
        cls,
        export_data: dict[str, dict[str, Any]],
        contaminant_manager: ContaminantManagerJSON | None = None,
    ) -> "StationManagerJSON":
        """Build from the `export_data` object returned by run_station_pipeline."""
        return cls(station_data_by_year=export_data, contaminant_manager=contaminant_manager)

    def set_contaminant_manager(self, contaminant_manager: ContaminantManagerJSON) -> None:
        """Attach or replace the contaminant manager used for enrichment queries."""
        self._contaminant_manager = contaminant_manager

    def get_available_years(self) -> list[int]:
        """Return sorted list of available years."""
        years: list[int] = []
        for year_key in self._stations_data_by_year.keys():
            try:
                years.append(int(year_key))
            except ValueError:
                continue

        years.sort()
        return years

    def has_year(self, year: int) -> bool:
        """Check if a year exists in station data."""
        return str(year) in self._stations_data_by_year

    def get_station_ids(self, year: int | None = None) -> list[str]:
        """Return station ids for one year, or all unique ids across all years."""
        if year is not None:
            year_key = str(year)
            if year_key not in self._stations_data_by_year:
                return []
            return sorted(self._stations_data_by_year[year_key].keys())

        all_ids: set[str] = set()
        for station_data in self._stations_data_by_year.values():
            all_ids.update(station_data.keys())

        return sorted(all_ids)

    def has_station(self, station_id: str | int, year: int | None = None) -> bool:
        """Check if a station exists in a year or in any year."""
        station_key = str(station_id)

        if year is not None:
            year_key = str(year)
            return (
                year_key in self._stations_data_by_year
                and station_key in self._stations_data_by_year[year_key]
            )

        return any(
            station_key in self._stations_data_by_year[str(y)]
            for y in self.get_available_years()
        )

    def get_station_data(self, station_id: str | int, year: int) -> dict[str, Any] | None:
        """Return one station record for a specific year."""
        station_key = str(station_id)
        year_key = str(year)

        if year_key not in self._stations_data_by_year:
            return None

        station_data = self._stations_data_by_year[year_key].get(station_key)
        if station_data is None:
            return None

        return copy.deepcopy(station_data)

    def get_latest_station_data(self, station_id: str | int) -> dict[str, Any] | None:
        """Return the latest available record for a station across all years."""
        station_key = str(station_id)
        years_desc = sorted(self.get_available_years(), reverse=True)

        for year in years_desc:
            year_key = str(year)
            if station_key in self._stations_data_by_year[year_key]:
                result = copy.deepcopy(self._stations_data_by_year[year_key][station_key])
                result["year"] = year
                return result

        return None

    def get_station_contaminant_codes(self, station_id: str | int, year: int) -> list[int] | None:
        """Return contaminant codes measured by a station in a given year."""
        station_data = self.get_station_data(station_id, year)
        if station_data is None:
            return None

        codes = station_data.get("contaminant_code")
        if not isinstance(codes, list):
            return None

        parsed_codes: list[int] = []
        for code in codes:
            try:
                parsed_codes.append(int(float(code)))
            except (TypeError, ValueError):
                continue

        return parsed_codes

    def get_station_contaminant_metadata(
        self,
        station_id: str | int,
        year: int,
    ) -> list[dict[str, Any]] | None:
        """Return contaminant metadata for all contaminants measured by a station.

        Requires an attached ContaminantManagerJSON.
        """
        if self._contaminant_manager is None:
            raise ValueError(
                "No ContaminantManagerJSON configured. "
                "Use set_contaminant_manager(...) or pass it in __init__."
            )

        codes = self.get_station_contaminant_codes(station_id, year)
        if codes is None:
            return None

        metadata_items: list[dict[str, Any]] = []
        for code in codes:
            summary = self._contaminant_manager.get_metadata_summary_by_code(code)
            metadata_items.append(summary if summary is not None else {"code": code, "description": "UNKNOWN"})

        return metadata_items

    def get_stations_measuring_contaminant(self, contaminant_code: int, year: int) -> list[str]:
        """Return station ids that measure a given contaminant code in a year."""
        year_key = str(year)
        if year_key not in self._stations_data_by_year:
            return []

        target_code = int(contaminant_code)
        matched: list[str] = []

        for station_id, station_data in self._stations_data_by_year[year_key].items():
            codes = station_data.get("contaminant_code", [])
            if not isinstance(codes, list):
                continue

            parsed_codes: list[int] = []
            for code in codes:
                try:
                    parsed_codes.append(int(float(code)))
                except (TypeError, ValueError):
                    continue

            if target_code in parsed_codes:
                matched.append(station_id)

        matched.sort()
        return matched

    def get_all_data(self) -> dict[str, Any]:
        """Return a deep copy of all station data by year."""
        return copy.deepcopy(self._stations_data_by_year)


