def main() -> None:
    """Run a lightweight manual test for all public StationManagerJSON methods."""

    print("=" * 80)
    print("StationManagerJSON manual test")
    print("=" * 80)

    demo_data = _build_demo_station_data()

    print("\n1) Construct from in-memory data")
    station_manager = StationManagerJSON(station_data_by_year=demo_data)
    print(station_manager)

    print("\n2) Construct from file path")
    with tempfile.NamedTemporaryFile(mode="w", suffix=".json", delete=False, encoding="utf-8") as tmp_file:
        json.dump(demo_data, tmp_file, indent=2)
        temp_path = tmp_file.name

    try:
        station_manager_from_file = StationManagerJSON(file_path=temp_path)
        print(station_manager_from_file)
    finally:
        os.unlink(temp_path)

    print("\n3) Build using from_pipeline_export_data")
    station_manager_from_pipeline = StationManagerJSON.from_pipeline_export_data(demo_data)
    print(station_manager_from_pipeline)

    print("\n4) get_available_years / has_year")
    years = station_manager.get_available_years()
    print("Available years:", years)
    print("Has year 2019:", station_manager.has_year(2019))
    print("Has year 2022:", station_manager.has_year(2022))

    print("\n5) get_station_ids / has_station")
    print("All station ids:", station_manager.get_station_ids())
    print("2019 station ids:", station_manager.get_station_ids(2019))
    print("Unknown year station ids:", station_manager.get_station_ids(2025))
    print("Has station '4' in any year:", station_manager.has_station("4"))
    print("Has station '8' in 2021:", station_manager.has_station("8", 2021))

    print("\n6) get_station_data / get_latest_station_data")
    pp.pprint(station_manager.get_station_data("4", 2019))
    pp.pprint(station_manager.get_station_data("999", 2019))
    pp.pprint(station_manager.get_latest_station_data("4"))
    pp.pprint(station_manager.get_latest_station_data("999"))

    print("\n7) get_station_contaminant_codes")
    print("Station 4, 2021:", station_manager.get_station_contaminant_codes("4", 2021))
    print("Station 999, 2021:", station_manager.get_station_contaminant_codes("999", 2021))

    print("\n8) get_station_contaminant_metadata without manager (expected error)")
    try:
        station_manager.get_station_contaminant_metadata("4", 2021)
    except ValueError as exc:
        print("Expected ValueError:", exc)

    print("\n9) set_contaminant_manager / get_station_contaminant_metadata")
    contaminants_json_path = "./../data/gold/contaminants/contaminants.json"
    if os.path.exists(contaminants_json_path):
        contaminant_manager = ContaminantManagerJSON(contaminants_json_path)
        station_manager.set_contaminant_manager(contaminant_manager)
        pp.pprint(station_manager.get_station_contaminant_metadata("4", 2021))
    else:
        print("Skipped integration test: contaminants JSON file not found at", contaminants_json_path)

    print("\n10) get_stations_measuring_contaminant")
    print("Stations measuring code 10 in 2019:", station_manager.get_stations_measuring_contaminant(10, 2019))
    print("Stations measuring code 999 in 2021:", station_manager.get_stations_measuring_contaminant(999, 2021))

    print("\n11) get_all_data")
    all_data = station_manager.get_all_data()
    pp.pprint(all_data)

    print("\nManual test completed.")


if __name__ == "__main__":
    main()
